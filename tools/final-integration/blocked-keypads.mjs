async function derivative(page, field, record, e) {
  if(!e.catalog) {
    // Native derivative generators avoid recent repeats. Rebuild the original
    // deterministic catalog in order rather than pretending a seed alone is its state.
    const item=JSON.parse(fs.readFileSync(root+'tools/mathlive-sitewide/artifacts/final-field-inventory.json')).find(r=>r.route===field.route);
    let plans=[{}];
    for(const [id,values] of Object.entries(item.selectors))if(id!=='practice-type')plans=plans.flatMap(p=>values.map(v=>({...p,[id]:v})));
    e.catalog=new Map();
    for(const selectors of plans) {
      for(const [id,v] of Object.entries(selectors))e.el(id).value=v;
      for(let seed=1;seed<=300;seed++) {
        e.b.BatchMathRNG.random=rng(seed*719);e.qa.makeProblem();
        const q=JSON.parse(JSON.stringify(e.qa.current));
        e.catalog.set(q.id,q);
      }
    }
  }
  const q=e.catalog.get(field.questionId);
  assert.ok(q,'Original question must be regenerated by the ordered native catalog');
  assert.equal(q.id, field.questionId, 'Original generated derivative question');
  assert.equal(q.answerExpr,field.requiredAnswer,'Original derivative answer is unchanged');
  const load = () => page.evaluate(({q, selectors}) => {
    for (const [id,v] of Object.entries(selectors)) { const s = document.getElementById(id); if (s) s.value=v; }
    window.__KEYPAD_FIXTURE={...q,answered:false};
    try { siteQA.makeProblem(); } finally { delete window.__KEYPAD_FIXTURE; }
  }, {q, selectors:field.selector});
  await load();
  const mf = page.locator('math-field:visible').first();
  record.wrongEntry=await enterAnswer(page,mf,'987654321');
  await click(page.locator('#submit'));
  assert.match(await page.locator('#feedback').getAttribute('class'),/wrong/);
  record.wrongRejected=true;
  await load();
  record.correctEntry=await enterAnswer(page,mf,field.requiredRepresentation || field.requiredAnswer);
  await click(page.locator('#submit'));
  assert.match(await page.locator('#feedback').getAttribute('class'),/correct/);
  record.correctAccepted=true;
}

async function dynamic(page, field, record, e) {
  const raw=evidence(field.evidence).results.find(r=>r.route===field.route&&r.questionId===field.questionId&&r.passed);
  assert.ok(raw, 'Original dynamic generation evidence');
  const q=JSON.parse(JSON.stringify(e.generate(raw.seed,raw.generatorSlug,raw.selector)));
  assert.equal(q.id,field.questionId,'Original generated dynamic question');
  const target=Number(field.part || 0), fieldIndex=Number(field.field || 0);
  async function run(wrong) {
    await replay(page,q);
    for(let turn=0;turn<=target;turn++) {
      const d=await info(page), box=await scope(page);
      assert.equal(d.index,turn);
      if(d.choice) {
        await click(box.locator('button.choice').nth(d.correctIndex));
      } else {
        let values=d.part?[d.raw]:expected(d.q);
        if(/list/.test(d.mode||''))values=values.map(v=>v.replace(/(^|,)\s*[a-z]\s*=/gi,'$1'));
        if(turn===target) {
          values=[...values];
          const correct=field.requiredRepresentation || field.requiredAnswer;
          const digits=/\.(\d+)/.exec(correct)?.[1].length || 0;
          const number='987654321'+(digits?'.'+'0'.repeat(digits):'');
          values[fieldIndex]=wrong?(/interval/.test(d.mode||'')||q.answerType==='interval-answer'?'('+number+',987654322'+(digits?'.'+'0'.repeat(digits):'')+')':number):correct;
        }
        const entries=[];
        for(const [i,v] of values.entries())entries.push(await enterAnswer(page,box.locator('math-field:visible').nth(i),v));
        await click(box.locator('button').filter({hasText:/^Check/}).first());
        if(turn===target&&wrong) {
          const feedback=(await box.innerText())+'\n'+await page.locator('#feedback').innerText();
          assert.equal(await box.locator('.result.good').count(),0);
          assert.match(feedback,/not correct|incorrect|not quite|needs? correction|does not match/i,feedback);
          record.wrongEntry=entries[fieldIndex];record.wrongRejected=true;record.wrongFeedback=feedback;
        } else {
          assert.ok(await box.locator('.result.good').count()||await page.locator('#feedback .result.good').count(),await box.innerText());
          if(turn===target){record.correctEntry=entries[fieldIndex];record.correctAccepted=true;}
        }
      }
      if(turn<target) {
        await click((await scope(page)).locator('.staged-continue:visible:enabled').first());
        await page.waitForFunction(previous=>{const p=[...document.querySelectorAll('.staged-part:not(.staged-completed)')].at(-1);return p&&(p.dataset.part!==undefined?+p.dataset.part:p.classList.contains('staged-part-two')?1:0)>previous;},turn);
      }
    }
  }
  await run(true); await run(false);
}

async function prep(page,field,record,e) {
  const witnesses=evidence(field.evidence).results.filter(r=>r.questionId===field.questionId&&r.question);
  const offset=degreeReplays.get(field.evidence)||0;
  const witness=witnesses[offset];degreeReplays.set(field.evidence,offset+1);
  let q=witness?.question&&typeof witness.question==='object'?witness.question:null;
  if(!q)q=e.generate(field.seed||719,field.selector||{mode:'reference',format:'degrees'});
  assert.equal(q.id,field.questionId);
  if(witness?.prior) {
    await page.locator('#mode').selectOption(witness.prior);
    await page.locator('#mode').selectOption('reference');
    await page.locator('#format').selectOption('degrees');
    record.priorMode=witness.prior;
  }
  const load=()=>page.evaluate(q=>prepQA.load(q),q);
  for(const wrong of [true,false]) {
    await load();
    const entry=await enterAnswer(page,page.locator('math-field:visible').first(),wrong?'31°':field.requiredAnswer);
    await click(page.locator('.bm-calc-keypad:visible button').filter({hasText:/^Check$/}));
    assert.equal(await page.locator('#feedback').getAttribute('class'),'feedback '+(wrong?'wrong':'correct'));
    if(wrong){record.wrongEntry=entry;record.wrongRejected=true;}else{record.correctEntry=entry;record.correctAccepted=true;}
  }
}

